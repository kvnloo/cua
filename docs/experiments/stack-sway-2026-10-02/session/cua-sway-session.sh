#!/usr/bin/env bash
# Headless multi-seat sway session for Driver/MCP/CUA experiments, isolated from the host desktop.
#   usage: hostless cua-sway-session.sh <cmd> [args...]
# Runs <cmd> as a child of a private headless sway 1.12 (wlroots 0.20, pixman renderer, no input
# devices) with Xwayland for X11 clients, a private dbus-run-session and optional private AT-SPI.
# <cmd> inherits WAYLAND_DISPLAY / SWAYSOCK / DISPLAY from the private sway itself.
#
# Knobs (environment of the caller; everything else is scrubbed by env -i):
#   CUA_SWAY_SEATS=n          seats seat0..seat<n-1> (default 1). seat0 is the fallback seat; seat1+
#                             own only virtual devices created against them (zwlr_virtual_pointer /
#                             zwp_virtual_keyboard with that wl_seat). Do not run "swaymsg seat ..."
#                             after virtual devices exist: sway re-applies attachment rules and moves
#                             them to the fallback seat.
#   CUA_SWAY_OUTPUTS=WxH[,WxH...]   headless outputs, laid out left to right (default 1920x1080).
#   CUA_SESSION_ATSPI=1       start a private AT-SPI bus + registry inside the private D-Bus.
#   CUA_SWAY_TIMEOUT=secs     hard stop for the whole session (default 1800).
#   CUA_SESSION_EXTRA_ENV="K=V ..."  extra variables passed into the scrubbed environment.
# Isolation layers: hostless (tmpfs over host X11/ICE dirs and /run/user/<uid>, desktop vars dropped)
#   + env -i + nested bwrap (private /tmp and PID namespace: teardown kills exactly the session tree)
#   + landlock-scope (no connect() to abstract unix sockets bound outside the session, e.g. the host
#   Xwayland's @/tmp/.X11-unix/X0, which tmpfs masks cannot hide; no signals to outside processes).
set -euo pipefail
die() { echo "[sway-session] refusing: $*" >&2; exit 97; }
[ "${CUA_HOSTLESS:-}" = 1 ] || die "not inside hostless (CUA_HOSTLESS!=1)"
[ -z "${WAYLAND_DISPLAY:-}${WAYLAND_SOCKET:-}" ] || die "WAYLAND_DISPLAY/WAYLAND_SOCKET is set"
[ -z "${SWAYSOCK:-}${I3SOCK:-}" ] || die "SWAYSOCK/I3SOCK is set"
if compgen -e | grep -q '^HYPRLAND_'; then die "HYPRLAND_* is set"; fi
[ $# -ge 1 ] || { echo "usage: cua-sway-session.sh <cmd> [args...]" >&2; exit 2; }

KIT=<KIT>
ART="$KIT/root"
NODE22=<NODE22>
SEATS="${CUA_SWAY_SEATS:-1}"; OUTPUTS="${CUA_SWAY_OUTPUTS:-1920x1080}"; TIMEOUT="${CUA_SWAY_TIMEOUT:-1800}"
[[ "$SEATS" =~ ^[1-8]$ ]] || die "CUA_SWAY_SEATS must be 1..8"
[[ "$OUTPUTS" =~ ^[0-9]+x[0-9]+(,[0-9]+x[0-9]+)*$ ]] || die "CUA_SWAY_OUTPUTS must be WxH[,WxH...]"
[[ "$TIMEOUT" =~ ^[0-9]+$ ]] || die "CUA_SWAY_TIMEOUT must be seconds"

RUN="$(mktemp -d <TMP>/sway-session.XXXXXX)"
chmod 700 "$RUN"; mkdir -p "$RUN/xdg-runtime" "$RUN/home" "$RUN/tmp" "$RUN/slash-tmp"; chmod 700 "$RUN/xdg-runtime"

# X display number: wlroots takes the lowest :n (0..32) whose /tmp/.X<n>-lock it can create and whose
# sockets it can bind. /tmp is private here, and a host display served by path sockets only (the host
# Hyprland Xwayland: /tmp/.X11-unix/X1 + X1_, no abstract socket) leaves @/tmp/.X11-unix/X<n> free in
# the shared network namespace, so the private Xwayland could claim it and host X11 clients that try the
# abstract socket first (libxcb) would land in this session. Seed a lock (owned by PID 1 of the session's
# PID namespace, always alive) for every display number the host uses in any form.
HOST_X="$( { for f in /tmp/.X*-lock; do [ -e "$f" ] && basename "$f"; done
             awk 'NR > 1 {print $NF}' /proc/net/unix; } \
           | sed -nE 's#^(\.X([0-9]+)-lock|@?/tmp/\.X11-unix/X([0-9]+)_?)$#\2\3#p' | sort -un | tr '\n' ' ')"
for n in $HOST_X; do [ "$n" -le 32 ] && printf '%10d\n' 1 > "$RUN/slash-tmp/.X$n-lock"; done
echo "$HOST_X" > "$RUN/host-x-displays"
free_x=0; for ((n = 0; n <= 32; n++)); do [ -e "$RUN/slash-tmp/.X$n-lock" ] || free_x=$((free_x + 1)); done
[ "$free_x" -gt 0 ] || die "no free X display number in 0..32"

CMD_FILE="$RUN/cmd.sh"
{ echo '#!/usr/bin/env bash'; echo 'set -uo pipefail'
  printf 'cd %q\n' "$PWD"
  printf 'exec'; for a in "$@"; do printf ' %q' "$a"; done; echo
} > "$CMD_FILE"; chmod 700 "$CMD_FILE"

# Generated sway config: headless outputs, N seats, Xwayland, payload launched by sway itself.
IFS=, read -ra OUTS <<< "$OUTPUTS"
{ echo "# generated by cua-sway-session.sh"
  echo "xwayland enable"
  echo "focus_follows_mouse yes"
  echo "default_border normal 2"
  x=0; i=1
  for o in "${OUTS[@]}"; do
    echo "output HEADLESS-$i resolution $o position $x,0 bg #202020 solid_color"
    x=$((x + ${o%x*})); i=$((i + 1))
  done
  echo "seat seat0 fallback true"
  for ((s = 1; s < SEATS; s++)); do echo "seat seat$s fallback false"; done
  echo "exec bash $RUN/payload.sh"
} > "$RUN/sway.config"

cat > "$RUN/payload.sh" <<PAYLOAD
#!/usr/bin/env bash
# Runs as a child of the private sway: WAYLAND_DISPLAY, SWAYSOCK and DISPLAY come from sway.
set -uo pipefail
exec 1>&3 2>&4 3>&- 4>&-   # caller's stdout/stderr, handed through sway by inner.sh
ok=0
for _ in \$(seq 1 150); do
  nout=\$(swaymsg -t get_outputs -r 2>/dev/null | grep -c '"active": true' || true)
  nseat=\$(swaymsg -t get_seats -r 2>/dev/null | grep -c '"name": "seat' || true)
  if [ "\$nout" = "${#OUTS[@]}" ] && [ "\$nseat" = "$SEATS" ] && xdpyinfo -display "\${DISPLAY:-}" >/dev/null 2>&1; then ok=1; break; fi
  sleep 0.2
done
dn=\${DISPLAY#:}; dn=\${dn%%.*}
for n in \$(cat "$RUN/host-x-displays"); do
  [ "\$n" = "\$dn" ] && { echo "[sway-session] refusing: private Xwayland :\$dn collides with a host display" >&2; ok=0; }
done
if [ \$ok = 1 ]; then
  echo "[sway-session] ready WAYLAND_DISPLAY=\$WAYLAND_DISPLAY DISPLAY=\$DISPLAY seats=$SEATS outputs=$OUTPUTS" >&2
  bash "$CMD_FILE"; rc=\$?
else
  echo "[sway-session] readiness wait failed (outputs=\${nout:-?} seats=\${nseat:-?} DISPLAY=\${DISPLAY:-unset})" >&2; rc=98
fi
echo \$rc > "$RUN/payload.rc"
swaymsg exit >/dev/null 2>&1
PAYLOAD

cat > "$RUN/inner.sh" <<INNER
#!/usr/bin/env bash
set -uo pipefail
if [ "\${CUA_SESSION_ATSPI:-0}" = "1" ]; then
  /usr/lib/at-spi-bus-launcher --launch-immediately >"$RUN/atspi-bus.log" 2>&1 &
  sleep 1
  /usr/lib/at-spi2-registryd --use-gnome-session >"$RUN/atspi-registry.log" 2>&1 &
fi
sway -c "$RUN/sway.config" 3>&1 4>&2 >"$RUN/sway.log" 2>&1 &
SW=\$!
( sleep $TIMEOUT; echo "[sway-session] timeout ${TIMEOUT}s: stopping sway" >&2; kill \$SW ) 2>/dev/null &
WD=\$!
wait \$SW; swrc=\$?
kill \$WD 2>/dev/null
if [ -f "$RUN/payload.rc" ]; then exit "\$(cat "$RUN/payload.rc")"; fi
echo "[sway-session] sway exited rc=\$swrc before the payload finished (see $RUN/sway.log)" >&2
exit 99
INNER
chmod 700 "$RUN/payload.sh" "$RUN/inner.sh"

set +e
env -i \
  HOME="$RUN/home" USER="$USER" LOGNAME="$USER" SHELL=/bin/bash LANG=C.UTF-8 TERM=xterm \
  PATH="$KIT/bin:$ART/usr/bin:$NODE22:<HOME>/.local/bin:<HOME>/.cargo/bin:/usr/local/bin:/usr/bin:/bin" \
  LD_LIBRARY_PATH="$ART/usr/lib" \
  XDG_DATA_DIRS="$ART/usr/share:/usr/local/share:/usr/share" XDG_CONFIG_DIRS="$ART/etc/xdg:/etc/xdg" \
  TMPDIR="$RUN/tmp" CUA_SWAY_RUN="$RUN" CUA_HOSTLESS=1 CUA_SESSION_ATSPI="${CUA_SESSION_ATSPI:-0}" \
  XDG_RUNTIME_DIR="$RUN/xdg-runtime" XDG_STATE_HOME="$RUN/home/.local/state" \
  XDG_CONFIG_HOME="$RUN/home/.config" XDG_CACHE_HOME="$RUN/home/.cache" XDG_DATA_HOME="$RUN/home/.local/share" \
  XDG_SESSION_TYPE=wayland XDG_CURRENT_DESKTOP=sway \
  WLR_BACKENDS=headless WLR_RENDERER=pixman WLR_LIBINPUT_NO_DEVICES=1 WLR_HEADLESS_OUTPUTS="${#OUTS[@]}" \
  UV_CACHE_DIR=<UV_CACHE> \
  ${CUA_SESSION_EXTRA_ENV:-} \
  bwrap --dev-bind / / --bind "$RUN/slash-tmp" /tmp --unshare-pid --proc /proc --die-with-parent -- \
  "$KIT/bin/landlock-scope" dbus-run-session -- bash "$RUN/inner.sh"
rc=$?
echo "[sway-session] exit rc=$rc run_dir=$RUN" >&2
exit $rc
